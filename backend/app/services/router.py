"""快慢分流（查询路由）模块。

设计原则（法律场景安全兜底）：
- 拿不准的问题一律走慢路径（完整 RAG 检索），宁可多检索，不可漏检索；
- 只有明确判定为「常识性/问候性」的问题才走快路径（LLM 直接回答）。
"""
from __future__ import annotations

import re

# ---- 快路径触发模式（命中即直接回答，不检索知识库） ----

# 问候 / 寒暄
GREETING_PATTERNS = [
    r"^(你好|您好|hi|hello|嗨|哈喽|在吗|早上好|下午好|晚上好|大家好)[!！。？?~～]*$",
    r"^(谢谢|感谢|多谢|辛苦了|再见|拜拜)[!！。？?~～]*$",
]

# 明确是「闲聊/身份/能力」类问题
SMALLTALK_PATTERNS = [
    r"(你是谁|你叫什么|介绍一下你|你能做什么|你会什么|你的能力|你是什么)",
    r"(谁创造了你|谁开发的你|你的作者|你是不是人|你有意识吗)",
    r"(帮我写(首)?诗|讲个笑话|编个故事|唱首歌)",
    r"(今天天气|现在几点|几点了|你在哪|你在哪里)",
]

# 明确是「通用常识概念」——与具体法条无关、属于通识教育范畴
# 注意：兼容中文全角问号「？」与英文半角「?」
_COMMON_CONCEPTS = r"(法律|法治|合同|债权|债务|物权|知识产权|刑法|民法|宪法|诉讼法|民法典|劳动合同法|公司法|婚姻法|继承法|行政处罚法|治安管理处罚法|律师|法官|公证|违约金|定金|抵押权|继承|遗嘱|婚姻|离婚|抚养权|劳动仲裁|工伤|交通事故|消费者权益)"
COMMON_SENSE_PATTERNS = [
    rf"^什么是{_COMMON_CONCEPTS}[？！?]?$",
    rf"^({_COMMON_CONCEPTS})是什么[？！?]?$",
    rf"^(介绍|解释)一下({_COMMON_CONCEPTS})的基本概念",
    r"^法律(与|和)道德(的|有|是)?(区别|关系|不同)",
    r"^合同(的|是)?(基本要素|成立条件|要素)有哪些",
    r"^(打官司|起诉|应诉)的(基本|一般)?(流程|步骤|程序)是什么",
]

# 明确要求走慢路径的强信号（法条/文件/具体规定）
SLOW_SIGNAL_PATTERNS = [
    r"第[一二三四五六七八九十百千0-9]+[条款章]",
    r"(民法典|刑法|宪法|劳动法|合同法|公司法|婚姻法|继承法|行政处罚法|刑事诉讼法|民事诉讼法|行政诉讼法|治安管理处罚法|劳动合同法|知识产权法|商标法|专利法|著作权法|反垄断法|消费者权益保护法|未成年人保护法|网络安全法|数据安全法|个人信息保护法|保险法|票据法|海商法|证券法|合伙企业法|个人独资企业法|外商投资法|产品质量法|食品安全法|药品管理法|环境保护法|土地管理法|城市房地产管理法|招标投标法|政府采购法|仲裁法|公证法|律师法|法官法|检察官法|人民调解法|行政复议法|国家赔偿法|立法法|监察法|审计法|统计法|会计法|预算法|税法|个人所得税法|企业所得税法|增值税法|印花税法|房产税|契税法|车船税法|船舶吨税法|资源税法|城市维护建设税法|关税法|慈善法|公益事业捐赠法|红十字会法|献血法|基本医疗卫生与健康促进法|医师法|中医药法|精神卫生法|传染病防治法|疫苗管理法|国境卫生检疫法|食品安全法|反食品浪费法|家庭教育促进法|学前教育法|职业教育法|高等教育法|教师法|科学技术进步法|科学技术普及法|促进科技成果转化法|农业技术推广法|农业法|畜牧法|渔业法|森林法|草原法|水法|水土保持法|防洪法|防沙治沙法|节约能源法|可再生能源法|清洁生产促进法|循环经济促进法|固体废物污染环境防治法|水污染防治法|大气污染防治法|噪声污染防治法|海洋环境保护法|湿地保护法|长江保护法|黄河保护法|黑土地保护法|青藏高原生态保护法|生物安全法|野生动物保护法|动物防疫法|种子法|农产品质量安全法|乡村振兴促进法|村民委员会组织法|城市居民委员会组织法|工会法|劳动法|就业促进法|社会保险法|军人地位和权益保障法|退役军人保障法|英雄烈士保护法|国家安全法|反间谍法|反恐怖主义法|反有组织犯罪法|保守国家秘密法|档案法|密码法|国防法|兵役法|军事设施保护法|国防教育法|人民防空法|突发事件应对法|防震减灾法|消防法|道路交通安全法|铁路法|民用航空法|邮政法|电信条例|电子商务法|电子签名法|网络安全法|数据安全法|个人信息保护法|人工智能法)[^，。]*",
    r"(司法解释|指导案例|公报案例|批复|答复|意见|决定|通知|规定|办法|条例|细则|规章|法规|法律修正案)",
]

# 中文里问句但含具体数字/时间/主体——保守走慢
CONSERVATIVE_PATTERNS = [
    r"(多少|几年|几岁|何时|什么时候|有效期|期限|时效|赔偿|处罚|罚金|刑期|拘留|逮捕|起诉|上诉|再审|仲裁|管辖|证据|举证|时效期间)",
]


def _match_any(text: str, patterns: list[str]) -> bool:
    return any(re.search(p, text) for p in patterns)


def route_query(query: str) -> str:
    """返回 'fast' 或 'slow'。

    fast = 常识/问候，直接回答；
    slow = 走完整 RAG 检索（保守默认）。
    """
    q = query.strip()
    if not q:
        return "slow"

    # 1) 问候/寒暄 → 快路径
    if _match_any(q, GREETING_PATTERNS):
        return "fast"

    # 2) 明确是「通用常识概念」→ 快路径
    #    必须先于 SLOW_SIGNAL 判断：如「民法典是什么」是常识，而「民法典第X条」不是
    if _match_any(q, COMMON_SENSE_PATTERNS):
        return "fast"

    # 3) 明确含法条/文件/具体规定的信号 → 慢路径（优先级最高）
    if _match_any(q, SLOW_SIGNAL_PATTERNS):
        return "slow"

    # 4) 闲聊/身份 → 快路径
    if _match_any(q, SMALLTALK_PATTERNS):
        return "fast"

    # 5) 保守信号（涉及具体权利义务/数字/程序）→ 慢路径
    if _match_any(q, CONSERVATIVE_PATTERNS):
        return "slow"

    # 6) 拿不准 → 慢路径（安全兜底）
    return "slow"
